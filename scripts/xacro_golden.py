"""Generate golden outputs with the official xacro implementation.

Runs the `xacro` Python package (pinned in scripts/requirements-golden.txt)
on every case in tests/corpus/cases.json and writes, per case, either
tests/corpus/golden/<id>.urdf (the expanded document, exactly as
`xacro` prints it, minus its "autogenerated" banner) or
tests/corpus/golden/<id>.error.txt (the error message).

ROS 2's xacro resolves $(find pkg) through ament_index_python, which is not
on PyPI. This script replaces that one lookup with the package folders
listed in the case; everything else is the unmodified xacro code. The
repository root is written as @ROOT@ so the files are the same on every
machine.

Usage: python scripts/xacro_golden.py            (writes the goldens)
       python scripts/xacro_golden.py --check    (fails if any golden would change)
"""

from __future__ import annotations

import io
import json
import sys
from contextlib import redirect_stderr
from pathlib import Path

import xacro
from xacro import substitution_args

ROOT = Path(__file__).resolve().parent.parent
CORPUS = ROOT / "tests" / "corpus"
GOLDEN = CORPUS / "golden"


def run_case(case: dict) -> tuple[str, str]:
    """Return ("urdf", text) or ("error", message) for one case."""
    packages = {name: (ROOT / rel).as_posix() for name, rel in case.get("packages", {}).items()}

    def find(pkg: str) -> str:
        if pkg in packages:
            return packages[pkg]
        raise LookupError(f"package '{pkg}' not found")

    substitution_args._eval_find = find  # type: ignore[attr-defined]
    substitution_args._eval_dict["find"] = find  # type: ignore[attr-defined]
    entry = (ROOT / case["entry"]).as_posix()
    xacro.all_includes = []
    stderr = io.StringIO()
    try:
        with redirect_stderr(stderr):
            xacro.init_stacks(entry)
            doc = xacro.parse(None, entry)
            xacro.process_doc(doc, mappings=dict(case.get("args", {})), verbosity=1)
        text = doc.toprettyxml(indent="  ")
        return "urdf", text.replace(ROOT.as_posix(), "@ROOT@")
    except Exception as e:  # noqa: BLE001 - every xacro failure is a golden "error" outcome
        # Paths in messages use the platform separator (and repr doubles it).
        msg = str(e) or repr(e)
        msg = msg.replace("\r\n", "\n").replace("\\\\", "/").replace("\\", "/")
        return "error", msg.replace(ROOT.as_posix(), "@ROOT@") + "\n"


def main() -> int:
    check = "--check" in sys.argv
    cases = json.loads((CORPUS / "cases.json").read_text(encoding="utf-8"))
    GOLDEN.mkdir(exist_ok=True)
    changed: list[str] = []
    expected_files = set()
    for case in cases:
        kind, text = run_case(case)
        name = f"{case['id']}.urdf" if kind == "urdf" else f"{case['id']}.error.txt"
        expected_files.add(name)
        path = GOLDEN / name
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            changed.append(name)
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
        print(f"{case['id']}: {kind}")
    stale = sorted(p.name for p in GOLDEN.iterdir() if p.name not in expected_files)
    if not check:
        for name in stale:
            (GOLDEN / name).unlink()
    print(f"xacro {xacro_version()}: {len(cases)} cases")
    if check and (changed or stale):
        print("golden files differ from the official xacro output:", *changed, *stale, sep="\n  ")
        return 1
    return 0


def xacro_version() -> str:
    from importlib.metadata import version

    return version("xacro")


if __name__ == "__main__":
    sys.exit(main())
