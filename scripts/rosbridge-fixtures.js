#!/usr/bin/env node
// Writes the message fixtures the fake rosbridge server replays
// (tests/fixtures/rosbridge/): 4 s of a simulated run of the mecanum
// template in the office (seed 1) as rosbridge "publish" messages for
// /tf_static, /tf, /odom, /scan, /imu and /joint_states, in the JSON form
// rosbridge_server sends (stamps as {sec, nanosec}; non-finite LaserScan
// ranges as null, and in every other scan as the bare Infinity token that
// Python's json module writes), plus the template's URDF as the
// robot_description. Simulator output, labelled so; not recorded from a robot.
// With --check, fails if the committed files differ.

import { mkdirSync, readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { generate } from "../src/core/builder/templates.js";
import { modelFromDoc } from "../src/core/builder/editor.js";
import { toUrdf } from "../src/core/builder/urdf.js";
import { simRobot } from "../src/core/sim/robot.js";
import { bundledWorld } from "../src/core/sim/world.js";
import { normalizeSettings } from "../src/core/sim/settings.js";
import { createSim, step } from "../src/core/sim/sim.js";
import { createRoute } from "../src/core/sim/routes.js";
import { recordingFiles } from "../src/core/sim/record.js";
import { parseRecording } from "../src/core/ros/recording.js";
import { bagMessages } from "../src/core/ros/bag.js";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "tests", "fixtures", "rosbridge");
const check = process.argv.includes("--check");

const doc = generate("mecanum", {});
const r = simRobot(modelFromDoc(doc), doc);
if (!r.ok) throw new Error(r.reason);
const world = /** @type {import("../src/core/sim/world.js").SimWorld} */ (bundledWorld("office"));
const sim = createSim(r.robot, world, normalizeSettings({ seed: 1 }), { log: true });
const route = createRoute("demo", r.robot, world);
for (let k = 0; k < 400; k++) step(sim, route.next(sim.drive, sim.t).twist);
const rec = parseRecording(
  recordingFiles(sim, { route: "demo", input: "mecanum", worldId: world.id }),
);

const KEEP = new Set(["/tf_static", "/tf", "/odom", "/scan", "/imu", "/joint_states"]);
/** Every other sample of the 100 Hz streams (rosbridge throttles them anyway). */
const EVERY = { "/tf": 2, "/imu": 2, "/joint_states": 2 };
/** @type {Record<string, number>} */
const seen = {};
const lines = [];
let scanNo = 0;
const msgs = bagMessages(rec);
const t0 = msgs[0].t;
for (const m of msgs) {
  if (!KEEP.has(m.topic)) continue;
  seen[m.topic] = (seen[m.topic] ?? 0) + 1;
  const every = /** @type {Record<string, number>} */ (EVERY)[m.topic] ?? 1;
  if ((seen[m.topic] - 1) % every !== 0) continue;
  let text = JSON.stringify({ op: "publish", topic: m.topic, msg: m.msg }, (_k, v) =>
    typeof v === "number" && !Number.isFinite(v) ? "__NONFINITE__" : v,
  );
  if (m.topic === "/scan") {
    // rosbridge_server's message conversion maps inf to null; Python's json writes Infinity.
    text = text.replaceAll('"__NONFINITE__"', scanNo++ % 2 ? "Infinity" : "null");
  }
  lines.push(
    JSON.stringify({ dt: Number((Number(m.t - t0) / 1e9).toFixed(3)), topic: m.topic, line: text }),
  );
}
const want = {
  "sim_mecanum.jsonl": lines.join("\n") + "\n",
  "robot_description.urdf": toUrdf(doc),
  "SOURCE.md":
    "# Fake rosbridge fixtures\n\n" +
    "Generated by `node scripts/rosbridge-fixtures.js` from a simulated run (mecanum template, office world, demo route, seed 1, 4 s): " +
    "rosbridge `publish` messages in the JSON form rosbridge_server sends, and the template's URDF as the robot_description. " +
    "Simulator output; nothing here was recorded from a robot.\n",
};
let bad = 0;
for (const [name, text] of Object.entries(want)) {
  const p = join(out, name);
  if (check) {
    if (!existsSync(p) || readFileSync(p, "utf8") !== text) {
      console.error(`differs: ${name}`);
      bad++;
    }
  } else {
    mkdirSync(out, { recursive: true });
    writeFileSync(p, text);
  }
}
if (bad) process.exit(1);
console.log(
  `${check ? "checked" : "wrote"} ${lines.length} messages and the robot_description in tests/fixtures/rosbridge`,
);
