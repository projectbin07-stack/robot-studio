// Exports of a builder document: URDF, xacro, the mecanum-kinematics TOML
// and a ROS 2 description package (zip). The package is a plain ament_cmake
// package with the URDF, an RViz launch file and config; its meshes are the
// mesh files the document refers to, copied from the opened files.

import { toUrdf, docToElement } from "./urdf.js";
import { templateXacro } from "./templates.js";
import { serializeXml } from "../xacro/serialize.js";
import { clone, rootLinks } from "./document.js";
import { mecanumConfig } from "./drive.js";
import { modelFromDoc } from "./editor.js";
import { writeZip } from "../zipwrite.js";
import { VERSION } from "../version.js";

/** @typedef {import("./document.js").RobotDoc} RobotDoc */
/** @typedef {import("../model.js").ModelFs} ModelFs */

/**
 * xacro for a document: the template's parametrised xacro when the document
 * is exactly what its template generates, else the URDF in a xacro file
 * (no parameters; it expands to the same URDF).
 * @param {RobotDoc} doc
 * @returns {{ text: string, parametrised: boolean }}
 */
export function exportXacro(doc) {
  const t = templateXacro(doc);
  if (t !== null) return { text: t, parametrised: true };
  const root = docToElement(doc);
  root.attrs["xmlns:xacro"] = "http://www.ros.org/wiki/xacro";
  root.prolog = [
    {
      type: "comment",
      value:
        ` Generated by Robot Studio ${VERSION}. Not parametrised: ` +
        (doc.template
          ? `the robot was edited after it was generated from the '${doc.template.id}' template, so its parameters no longer describe it. `
          : "the robot was not made from a template. ") +
        "Expands to the same URDF as the URDF export. ",
    },
  ];
  return { text: serializeXml(root), parametrised: false };
}

/** ROS package names (REP 144). */
export const PACKAGE_NAME_RE = /^[a-z][a-z0-9_]*$/;

/**
 * @typedef {object} PackageOptions
 * @property {string} [packageName] default: <robot name>_description
 * @property {ModelFs & { readBinary?: (path: string) => Promise<Uint8Array | null> } | null} [meshFs]
 * @property {string} [maintainer]
 * @property {string} [email]
 * @property {string} [license]
 */

/**
 * @typedef {object} PackageExport
 * @property {string} name
 * @property {{ path: string, data: Uint8Array | string }[]} files
 * @property {string[]} notes
 */

/** @param {string} s */
const xmlText = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/**
 * Files of a ROS 2 description package for the document.
 * @param {RobotDoc} input
 * @param {PackageOptions} [opts]
 * @returns {Promise<PackageExport>}
 */
export async function buildPackage(input, opts = {}) {
  const doc = clone(input);
  const pkg =
    opts.packageName ??
    `${
      doc.name
        .toLowerCase()
        .replace(/[^a-z0-9_]/g, "_")
        .replace(/^[^a-z]+/, "") || "robot"
    }_description`;
  if (!PACKAGE_NAME_RE.test(pkg))
    throw new RangeError(
      `'${pkg}' is not a valid ROS package name (lower case letters, digits and _, starting with a letter)`,
    );
  /** @type {string[]} */
  const notes = [];
  /** @type {{ path: string, data: Uint8Array | string }[]} */
  const files = [];

  // Meshes: copy each referenced file into meshes/ and point the URDF at it.
  const fs = opts.meshFs ?? null;
  const entry = doc.source?.entry ?? "/";
  /** @type {Map<string, string>} resolved path -> package path */
  const copied = new Map();
  const used = new Set();
  for (const link of doc.links)
    for (const s of [...link.visuals, ...link.collisions]) {
      const g = s.geometry;
      if (g.type !== "mesh") continue;
      const res = fs?.resolveUri
        ? fs.resolveUri(g.filename, entry)
        : { path: null, reason: "no files were opened with this robot" };
      if (!res.path || !fs?.readBinary) {
        notes.push(
          `mesh '${g.filename}' of link '${link.name}' was not copied (${res.reason || "cannot read files"}); the URDF still refers to it`,
        );
        continue;
      }
      let rel = copied.get(res.path);
      if (rel === undefined) {
        const base = res.path.split("/").pop() ?? "mesh";
        rel = base;
        for (let k = 2; used.has(rel); k++)
          rel = base.replace(/(\.[^.]*)?$/, (ext) => `_${k}${ext}`);
        used.add(rel);
        const bytes = await fs.readBinary(res.path);
        if (!bytes) {
          notes.push(`mesh '${g.filename}' could not be read; not copied`);
          continue;
        }
        files.push({ path: `${pkg}/meshes/${rel}`, data: bytes });
        copied.set(res.path, rel);
      }
      g.filename = `package://${pkg}/meshes/${rel}`;
    }

  const robot = doc.name;
  const hasMeshes = copied.size > 0;
  files.push({ path: `${pkg}/urdf/${robot}.urdf`, data: toUrdf(doc) });
  const x = exportXacro(input);
  if (x.parametrised) files.push({ path: `${pkg}/urdf/${robot}.urdf.xacro`, data: x.text });
  else
    notes.push(
      "no xacro file: the robot is not exactly a template's output (see the xacro export)",
    );
  const model = modelFromDoc(input, opts.meshFs ?? null);
  const toml = mecanumConfig(model);
  if (toml.ok) files.push({ path: `${pkg}/config/mecanum_kinematics.toml`, data: toml.toml });

  const dirs = [
    "launch",
    "rviz",
    "urdf",
    ...(hasMeshes ? ["meshes"] : []),
    ...(toml.ok ? ["config"] : []),
  ].sort();
  const maintainer = opts.maintainer ?? "Your Name";
  const email = opts.email ?? "you@example.com";
  const license = opts.license ?? "MIT";
  files.push({
    path: `${pkg}/package.xml`,
    data: `<?xml version="1.0"?>
<?xml-model href="http://download.ros.org/schema/package_format3.xsd" schematypens="http://www.w3.org/2001/XMLSchema"?>
<package format="3">
  <name>${pkg}</name>
  <version>0.1.0</version>
  <description>Robot description of ${xmlText(robot)} (URDF, RViz launch). Generated by Robot Studio ${VERSION}.</description>
  <!-- Set the maintainer and licence before publishing this package. -->
  <maintainer email="${xmlText(email)}">${xmlText(maintainer)}</maintainer>
  <license>${xmlText(license)}</license>

  <buildtool_depend>ament_cmake</buildtool_depend>

  <exec_depend>joint_state_publisher</exec_depend>
  <exec_depend>joint_state_publisher_gui</exec_depend>
  <exec_depend>launch</exec_depend>
  <exec_depend>launch_ros</exec_depend>
  <exec_depend>robot_state_publisher</exec_depend>
  <exec_depend>rviz2</exec_depend>
  <exec_depend>xacro</exec_depend>

  <export>
    <build_type>ament_cmake</build_type>
  </export>
</package>
`,
  });
  files.push({
    path: `${pkg}/CMakeLists.txt`,
    data: `cmake_minimum_required(VERSION 3.8)
project(${pkg})

find_package(ament_cmake REQUIRED)

install(DIRECTORY ${dirs.join(" ")}
  DESTINATION share/\${PROJECT_NAME})

ament_package()
`,
  });
  files.push({
    path: `${pkg}/launch/display.launch.py`,
    data: `# Generated by Robot Studio ${VERSION}: the robot in RViz with joint sliders.
#   ros2 launch ${pkg} display.launch.py            (joint_state_publisher_gui)
#   ros2 launch ${pkg} display.launch.py gui:=false (joint_state_publisher)
import os

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument
from launch.conditions import IfCondition, UnlessCondition
from launch.substitutions import LaunchConfiguration
from launch_ros.actions import Node


def generate_launch_description():
    share = get_package_share_directory("${pkg}")
    with open(os.path.join(share, "urdf", "${robot}.urdf"), encoding="utf-8") as f:
        robot_description = f.read()
    gui = LaunchConfiguration("gui")
    return LaunchDescription(
        [
            DeclareLaunchArgument(
                "gui",
                default_value="true",
                description="Start joint_state_publisher_gui (true) or joint_state_publisher (false)",
            ),
            Node(
                package="robot_state_publisher",
                executable="robot_state_publisher",
                parameters=[{"robot_description": robot_description}],
            ),
            Node(
                package="joint_state_publisher_gui",
                executable="joint_state_publisher_gui",
                condition=IfCondition(gui),
            ),
            Node(
                package="joint_state_publisher",
                executable="joint_state_publisher",
                condition=UnlessCondition(gui),
            ),
            Node(
                package="rviz2",
                executable="rviz2",
                arguments=["-d", os.path.join(share, "rviz", "display.rviz")],
            ),
        ]
    )
`,
  });
  const fixed = rootLinks(doc)[0] ?? "base_link";
  files.push({
    path: `${pkg}/rviz/display.rviz`,
    data: `Panels:
  - Class: rviz_common/Displays
    Name: Displays
Visualization Manager:
  Class: ""
  Displays:
    - Class: rviz_default_plugins/Grid
      Enabled: true
      Name: Grid
      Reference Frame: <Fixed Frame>
    - Class: rviz_default_plugins/RobotModel
      Enabled: true
      Name: RobotModel
      Description Source: Topic
      Description Topic:
        Value: /robot_description
    - Class: rviz_default_plugins/TF
      Enabled: true
      Name: TF
  Global Options:
    Fixed Frame: ${fixed}
  Tools:
    - Class: rviz_default_plugins/Interact
    - Class: rviz_default_plugins/MoveCamera
  Views:
    Current:
      Class: rviz_default_plugins/Orbit
      Distance: 1.5
      Focal Point:
        X: 0
        Y: 0
        Z: 0.1
`,
  });
  files.push({
    path: `${pkg}/README.md`,
    data: `# ${pkg}

Robot description of \`${robot}\`, generated by
[Robot Studio](https://github.com/projectbin07-stack/robot-studio) ${VERSION}.

\`\`\`bash
# in a colcon workspace: src/${pkg}
colcon build --packages-select ${pkg}
source install/setup.bash
ros2 launch ${pkg} display.launch.py
\`\`\`

Contents: \`urdf/${robot}.urdf\`${x.parametrised ? ` and the parametrised \`urdf/${robot}.urdf.xacro\`` : ""}${hasMeshes ? ", meshes in `meshes/`" : ""}${toml.ok ? ", a [mecanum-kinematics](https://github.com/projectbin07-stack/mecanum-kinematics) config in `config/`" : ""}, \`launch/display.launch.py\` (robot_state_publisher, joint_state_publisher(_gui), RViz) and \`rviz/display.rviz\`.

Set the maintainer and licence in \`package.xml\` before publishing.
The model is software-generated: check masses, dimensions and joint
limits against the real robot.
`,
  });
  files.sort((a, b) => (a.path < b.path ? -1 : 1));
  return { name: pkg, files, notes };
}

/**
 * The package as a zip archive.
 * @param {RobotDoc} doc
 * @param {PackageOptions} [opts]
 */
export async function packageZip(doc, opts = {}) {
  const p = await buildPackage(doc, opts);
  return { name: p.name, zip: writeZip(p.files), notes: p.notes };
}
