#!/usr/bin/env node
// Vendor upstream code at pinned versions, or verify the vendored copy.
//
//   node scripts/vendor.mjs            fetch every source and (re)write vendor/ and vendor/manifest.json
//   node scripts/vendor.mjs --verify   fetch every source again and fail if any vendored byte differs
//
// Git sources are cloned at their tag (shallow); npm sources are fetched
// with `npm pack`, which checks the registry integrity hash. Nothing in
// vendor/ is edited by hand: change the pins in scripts/vendor-lib.js and
// run this script.

import { execFileSync, execSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  SOURCES,
  compareWithUpstream,
  listFiles,
  readTarGz,
  sha256,
  verifyAgainstManifest,
} from "./vendor-lib.js";

/** @typedef {import("./vendor-lib.js").Source} Source */
/** @typedef {import("./vendor-lib.js").ManifestEntry} ManifestEntry */
/** @typedef {import("./vendor-lib.js").Manifest} Manifest */

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const manifestPath = join(root, "vendor", "manifest.json");
const verify = process.argv.includes("--verify");

/**
 * @param {string} cmd
 * @param {string[]} args
 * @param {string} [cwd]
 */
const run = (cmd, args, cwd) => {
  /** @type {import("node:child_process").ExecSyncOptionsWithStringEncoding} */
  const opts = { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "inherit"] };
  // npm is a .cmd script on Windows and needs a shell; the arguments are fixed strings from SOURCES.
  if (process.platform === "win32" && cmd === "npm")
    return execSync([cmd, ...args.map((a) => `"${a}"`)].join(" "), opts);
  return execFileSync(cmd, args, opts);
};

/**
 * Fetch one source into memory.
 * @param {Source} src
 * @param {string} work scratch directory
 * @returns {{ files: Map<string, Uint8Array>, meta: Partial<ManifestEntry> }}
 */
function fetchSource(src, work) {
  /** @type {Map<string, Uint8Array>} */
  const files = new Map();
  if (src.kind === "git") {
    const dir = join(work, src.name);
    run("git", [
      "-c",
      "core.autocrlf=false",
      "-c",
      "advice.detachedHead=false",
      "clone",
      "--quiet",
      "--depth",
      "1",
      "--branch",
      src.tag,
      src.repo,
      dir,
    ]);
    const commit = run("git", ["rev-parse", "HEAD"], dir).trim();
    for (const f of listFiles(dir).filter((p) => !p.startsWith(".git/")))
      files.set(f, readFileSync(join(dir, f)));
    return { files, meta: { repo: src.repo, tag: src.tag, commit } };
  }
  const out = run("npm", [
    "pack",
    `${src.package}@${src.version}`,
    "--json",
    "--silent",
    "--pack-destination",
    work,
  ]);
  const info = JSON.parse(out)[0];
  for (const [p, bytes] of readTarGz(readFileSync(join(work, info.filename))))
    files.set(p.replace(/^package\//, ""), bytes);
  return {
    files,
    meta: { package: src.package, version: src.version, integrity: info.integrity },
  };
}

const work = mkdtempSync(join(process.env.TMP ?? tmpdir(), "vendor-"));
try {
  if (verify) {
    /** @type {Manifest} */
    const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
    const problems = verifyAgainstManifest(manifest, root);
    for (const entry of manifest.sources) {
      const src = SOURCES.find((s) => s.name === entry.name);
      if (!src) {
        problems.push(`${entry.name}: in the manifest but not in scripts/vendor-lib.js`);
        continue;
      }
      const { files, meta } = fetchSource(src, work);
      if (meta.commit && meta.commit !== entry.commit)
        problems.push(
          `${entry.name}: tag ${entry.tag} now points to ${meta.commit}, manifest says ${entry.commit}`,
        );
      if (meta.integrity && meta.integrity !== entry.integrity)
        problems.push(
          `${entry.name}: npm integrity ${meta.integrity} != manifest ${entry.integrity}`,
        );
      problems.push(...compareWithUpstream(entry, files, root));
      console.log(
        `${entry.name}: compared ${entry.files.length} files with ${meta.tag ?? meta.version}`,
      );
    }
    if (problems.length > 0) {
      console.error(`vendored files do not match upstream:\n  ${problems.join("\n  ")}`);
      process.exit(1);
    }
    console.log("vendor: every vendored file matches its pinned upstream version");
  } else {
    /** @type {Manifest} */
    const manifest = {
      comment:
        "Generated by scripts/vendor.mjs. Do not edit vendored files; CI re-fetches each source and compares the bytes.",
      sources: [],
    };
    for (const src of SOURCES) {
      const { files, meta } = fetchSource(src, work);
      rmSync(join(root, src.dest), { recursive: true, force: true });
      /** @type {ManifestEntry} */
      const entry = {
        name: src.name,
        kind: src.kind,
        ...meta,
        license: src.license,
        dest: src.dest,
        files: [],
      };
      for (const f of src.files) {
        const bytes = files.get(f);
        if (!bytes) throw new Error(`${src.name}: ${f} not found upstream`);
        const target = join(root, src.dest, f);
        mkdirSync(dirname(target), { recursive: true });
        writeFileSync(target, bytes);
        entry.files.push({ path: f, sha256: sha256(bytes) });
      }
      manifest.sources.push(entry);
      console.log(`${src.name}: vendored ${src.files.length} files`);
    }
    writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + "\n");
  }
} finally {
  rmSync(work, { recursive: true, force: true });
}
