// Generate the two small meshes of the bundled studio_mecanum example: a
// LiDAR puck as binary STL and a depth-camera body as OBJ. Original
// geometry, written for this project; units are metres.
//
//   node scripts/make_example_meshes.js

import { mkdirSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const dir = fileURLToPath(new URL("../examples/studio_mecanum/meshes/", import.meta.url));
mkdirSync(dir, { recursive: true });

/** @typedef {[number, number, number]} V */

/**
 * Closed cylinder between z0 and z1 as triangles.
 * @param {number} r
 * @param {number} z0
 * @param {number} z1
 * @param {number} n
 * @returns {[V, V, V][]}
 */
function cylinder(r, z0, z1, n) {
  /** @type {[V, V, V][]} */
  const tris = [];
  for (let k = 0; k < n; k++) {
    const a = (2 * Math.PI * k) / n;
    const b = (2 * Math.PI * (k + 1)) / n;
    /** @type {V} */ const p0 = [r * Math.cos(a), r * Math.sin(a), z0];
    /** @type {V} */ const p1 = [r * Math.cos(b), r * Math.sin(b), z0];
    /** @type {V} */ const q0 = [p0[0], p0[1], z1];
    /** @type {V} */ const q1 = [p1[0], p1[1], z1];
    tris.push([p0, p1, q1], [p0, q1, q0]);
    tris.push([[0, 0, z1], q0, q1], [[0, 0, z0], p1, p0]);
  }
  return tris;
}

/** @param {V} a @param {V} b @param {V} c @returns {V} */
function normal(a, b, c) {
  const u = [b[0] - a[0], b[1] - a[1], b[2] - a[2]];
  const v = [c[0] - a[0], c[1] - a[1], c[2] - a[2]];
  const n = [u[1] * v[2] - u[2] * v[1], u[2] * v[0] - u[0] * v[2], u[0] * v[1] - u[1] * v[0]];
  const l = Math.hypot(n[0], n[1], n[2]) || 1;
  return [n[0] / l, n[1] / l, n[2] / l];
}

// LiDAR: a base puck (r 35 mm, 25 mm high), a narrower rotating head with a
// window band. Origin at the bottom centre; the scan plane is at z = 30 mm.
const lidar = [
  ...cylinder(0.035, 0, 0.022, 48),
  ...cylinder(0.031, 0.022, 0.026, 48),
  ...cylinder(0.028, 0.026, 0.036, 48),
  ...cylinder(0.03, 0.036, 0.04, 48),
];
const stl = Buffer.alloc(84 + 50 * lidar.length);
stl.write("studio_mecanum lidar, generated by scripts/make_example_meshes.js", 0, "ascii");
stl.writeUInt32LE(lidar.length, 80);
lidar.forEach((t, i) => {
  const o = 84 + 50 * i;
  const n = normal(...t);
  [...n, ...t[0], ...t[1], ...t[2]].forEach((v, k) => stl.writeFloatLE(v, o + 4 * k));
});
writeFileSync(`${dir}lidar.stl`, stl);

// Depth camera: a 90 x 25 x 25 mm body (x forward) with two lens discs on
// the front face. Origin at the body centre.
/** @type {V[]} */
const verts = [];
/** @type {number[][]} */
const faces = [];
/**
 * @param {V} c centre
 * @param {V} h half sizes
 */
function box(c, h) {
  const base = verts.length;
  for (const sx of [-1, 1])
    for (const sy of [-1, 1])
      for (const sz of [-1, 1]) verts.push([c[0] + sx * h[0], c[1] + sy * h[1], c[2] + sz * h[2]]);
  const f = [
    [0, 1, 3, 2],
    [4, 6, 7, 5],
    [0, 4, 5, 1],
    [2, 3, 7, 6],
    [0, 2, 6, 4],
    [1, 5, 7, 3],
  ];
  for (const q of f) faces.push(q.map((i) => base + i + 1));
}
/**
 * Disc facing +x.
 * @param {number} y
 * @param {number} r
 */
function lens(y, r) {
  const n = 24;
  const x = 0.0125 + 0.002;
  const centre = verts.length + 1;
  verts.push([x, y, 0]);
  for (let k = 0; k < n; k++) {
    const a = (2 * Math.PI * k) / n;
    verts.push([x, y + r * Math.cos(a), r * Math.sin(a)]);
  }
  for (let k = 0; k < n; k++) faces.push([centre, centre + 1 + k, centre + 1 + ((k + 1) % n)]);
}
box([0, 0, 0], [0.0125, 0.045, 0.0125]);
box([0.0135, 0, 0], [0.001, 0.04, 0.009]);
lens(-0.025, 0.006);
lens(0.025, 0.006);
const obj = [
  "# studio_mecanum depth camera, generated by scripts/make_example_meshes.js",
  "o camera_body",
  ...verts.map((v) => `v ${v.map((x) => x.toFixed(5)).join(" ")}`),
  ...faces.map((f) => `f ${f.join(" ")}`),
  "",
].join("\n");
writeFileSync(`${dir}camera.obj`, obj);
console.log(`wrote ${lidar.length} triangles to lidar.stl and ${faces.length} faces to camera.obj`);
